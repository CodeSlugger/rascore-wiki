HIDE = {"per_exchange", "terminal_app", "terminal_binding", "tiger_link"}
TYPE_RU = {"int": "число", "float": "число", "bool": "вкл/выкл", "list": "список", "exchanges": "биржи",
           "markets": "рынки", "select": "выбор", "tiers": "группы порогов", "multi": "выбор", "str": "текст"}


def val(x):
    d = x.get("default")
    t = x.get("type")
    if t == "bool":
        return "вкл" if d else "выкл"
    if t == "exchanges" and isinstance(d, dict):
        on = [k for k, v in d.items() if v]
        return ", ".join(on) if len(on) < 6 else "все"
    if t == "markets":
        return {"perp": "фьючерсы", "spot": "спот"}.get(d[0], d[0]) if len(d or []) == 1 else "фьючерсы и спот"
    if t == "tiers":
        return "; ".join(f"{', '.join(g.get('symbols', []))} — от {g.get('move_pct')}%" for g in d or []) or "нет"
    if isinstance(d, list):
        return "пусто" if not d else ", ".join(map(str, d))[:60]
    if isinstance(d, dict):
        return ", ".join(f"{k}: {v}" for k, v in d.items())[:80] or "—"
    if isinstance(d, float) and d.is_integer():
        d = int(d)
    if isinstance(d, (int, float)) and abs(d) >= 10000:
        return f"{d:,}".replace(",", " ")
    return str(d)


def table(typ):
    rows = ["| Настройка | Что задаёт | По умолчанию |", "|---|---|---|"]
    for x in S["schemas"].get(typ, []):
        if x["key"] in HIDE:
            continue
        lim = []
        if "min" in x or "max" in x:
            lim.append(f"от {x.get('min', '—')} до {x.get('max', '—')}")
        if x.get("options") and x["key"] != "sound":
            lim.append(", ".join(map(str, x["options"]))[:120])
        what = TYPE_RU.get(x.get("type"), "") + (f" ({'; '.join(lim)})" if lim else "")
        rows.append(f"| {str(x.get('label', '')).replace('|', '/')} | {what.replace('|', '/')} | {val(x).replace('|', '/')} |")
    return "\n".join(rows) + "\n"


